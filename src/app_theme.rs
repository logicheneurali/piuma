//! GTK/Qt theme bridge (roadmap N3): renders the bar's **character**,
//! **background/colours** and **borders** as a GTK stylesheet written
//! inside piuma's own config directory (`<config dir>/theme/gtk.css`),
//! so GTK applications can adopt the bar's style through a one-time
//! `@import` in the user's `gtk.css`. piuma never edits the user's
//! GTK/Qt files, and the palette keeps its own `@piuma_*` names so an
//! existing customisation (e.g. KDE/Breeze) keeps winning where it sets
//! the same property — the bridge only fills the gaps.
//!
//! GTK_THEME path: piuma also writes a real GTK theme dir at
//! `~/.local/share/themes/Piuma` (dark: `adw-gtk3` base + piuma palette),
//! so apps that follow `GTK_THEME` pick it up automatically — no
//! `@import` needed. piuma adds `GTK_THEME=Piuma` to the env block.
//!
//! Qt half: Qt picks its platform theme from the environment only, so
//! the bridge keeps one marked `QT_QPA_PLATFORMTHEME` block in
//! Hyprland's own config (added and removed with the same toggle; the
//! only user file piuma writes, and only between its two markers).

use std::path::Path;

use crate::config;
use crate::palette;

/// Ownership marker: the first line of every generated file; also what
/// `remove_ours` checks before deleting, so a user's own stylesheet
/// living at the same path is never touched.
const HEADER: &str = "/* generated by piuma (N3 theme bridge) — do not edit */";

/// Remove the generated file while the feature is off — but only a file
/// piuma wrote (identified by [`HEADER`]); anything else at that path
/// belongs to the user and stays untouched.
fn remove_ours(file: &Path) {
    let Ok(existing) = std::fs::read_to_string(file) else { return };
    if !existing.starts_with(HEADER) {
        return;
    }
    match std::fs::remove_file(file) {
        Ok(()) => eprintln!("[piuma] app theme bridge removed: {}", file.display()),
        Err(err) => eprintln!("[piuma] app theme bridge: cannot remove {}: {err}", file.display()),
    }
}

/// Sync the bridge with the config and the runtime wallpaper palette:
/// generate it when `panel.app_theme` is on, otherwise drop piuma's own
/// file (a stale bridge would keep styling apps after the toggle goes
/// off). Called at startup, on every config hot reload and on every
/// palette arrival (the bar changes tone with the wallpaper — the
/// bridge must follow); the write itself skips unchanged content.
pub fn sync(config_path: &Path, panel: &config::PanelConfig, pal: Option<&palette::Palette>) {
    let Some(dir) = config_path.parent() else {
        return;
    };
    let file = dir.join("theme").join("gtk.css");
    if panel.app_theme.unwrap_or(false) {
        write(&file, &render(panel, pal));
        sync_theme_dir(panel, pal);
    } else {
        remove_ours(&file);
        remove_theme_dir();
    }
    sync_qt(panel);
}

/// Qt side of the bridge: keep the marked [`QT_BEGIN`] block in
/// Hyprland's config in step with `panel.app_theme`. The compositor
/// reads `hl.env` at load time only — a runtime `hyprctl eval
/// 'hl.env(..)'` never reaches the children (verified on this fork) —
/// so a file change is applied with a `reload config-only` (monitors
/// untouched); no change, no reload. The file is never created: a
/// system without Hyprland simply keeps its own config.
fn sync_qt(panel: &config::PanelConfig) {
    let Some(dir) = dirs::config_dir() else {
        return;
    };
    let file = dir.join("hypr").join("hyprland.lua");
    if !file.exists() {
        return;
    }
    let Ok(existing) = std::fs::read_to_string(&file) else {
        return;
    };
    let enabled = panel.app_theme.unwrap_or(false);
    let Some(updated) = qt_applied(&existing, enabled) else {
        return;
    };
    if let Err(err) = std::fs::write(&file, &updated) {
        eprintln!("[piuma] Qt theme bridge: cannot write {}: {err}", file.display());
        return;
    }
    eprintln!(
        "[piuma] Qt theme bridge {}: {}",
        if enabled { "written" } else { "removed" },
        file.display()
    );
    // Swallow hyprctl's output: piuma's stdout belongs to the bar.
    let _ = std::process::Command::new("hyprctl")
        .args(["reload", "config-only"])
        .output();
}

/// Boundaries of piuma's own block in the compositor config: a removal
/// touches nothing outside them, whatever the user wrote around.
const QT_BEGIN: &str = "-- generated by piuma (Qt theme bridge) — do not edit";
const QT_END: &str = "-- end piuma Qt theme bridge";

/// The block as it is written (appended at the end of the config).
fn qt_block() -> String {
    format!("{QT_BEGIN}\nhl.env(\"GTK_THEME\", \"Piuma\")\nhl.env(\"QT_QPA_PLATFORMTHEME\", \"gtk3\")\n{QT_END}\n")
}

/// The config with piuma's Qt block in the requested state, `None` when
/// that leaves the file byte-identical (an unchanged run must not touch
/// the file nor reload the compositor). Disabling a config piuma never
/// touched stays a no-op, so a foreign file is never rewritten.
fn qt_applied(existing: &str, enabled: bool) -> Option<String> {
    if !enabled && !existing.contains(QT_BEGIN) {
        return None;
    }
    // Rebuilding line by line also normalises a missing final newline,
    // which is why the result is compared against the original.
    let base: String = {
        let mut out = String::new();
        let mut skipping = false;
        for line in existing.lines() {
            if line == QT_BEGIN {
                skipping = true;
                continue;
            }
            if skipping {
                if line == QT_END {
                    skipping = false;
                }
                continue;
            }
            out.push_str(line);
            out.push('\n');
        }
        out
    };
    let target = if enabled { format!("{base}{}", qt_block()) } else { base };
    (target != existing).then_some(target)
}

/// The bridge stylesheet: the bar's own fallbacks apply (`panel.font`,
/// `default_bg_color`/`default_text_color`, the `-1 = disabled` rule for
/// border numbers via `style_num`), alpha is dropped on the background
/// (GTK windows are opaque) and no border rule is emitted when the bar
/// itself shows none (`sensor_defaults`/`section_defaults` unset).
fn render(panel: &config::PanelConfig, pal: Option<&palette::Palette>) -> String {
    // Character: family/size/bold, same defaults as the bar.
    let font = panel
        .font
        .as_deref()
        .filter(|f| !f.is_empty())
        .unwrap_or(crate::DEFAULT_FONT)
        .replace('"', "");
    let size = panel.font_size.unwrap_or(crate::DEFAULT_FONT_SIZE);
    let bold = panel.bold.unwrap_or(false);
    // Background/colours through the bar's own resolution (runtime
    // wallpaper palette first, same precedence as the bar renders);
    // alpha is dropped — GTK windows are opaque.
    let bg = rgb_hex(crate::styles::panel_bg(panel, pal));
    let fg = rgb_hex(crate::styles::default_text(panel, pal));
    let border = border_style(panel);

    let mut css = String::new();
    css.push_str(HEADER);
    css.push_str("\n\n/* palette (own names: the user's palette keeps winning) */\n");
    css.push_str(&format!("@define-color piuma_bg {bg};\n"));
    css.push_str(&format!("@define-color piuma_fg {fg};\n"));
    if let Some(color) = border.as_ref().and_then(|b| b.0.as_deref()) {
        css.push_str(&format!("@define-color piuma_border {color};\n"));
    }

    css.push_str("\n/* character */\n* {\n");
    css.push_str(&format!("  font-family: \"{font}\";\n"));
    css.push_str(&format!("  font-size: {size}px;\n"));
    if bold {
        css.push_str("  font-weight: bold;\n");
    }
    css.push_str("}\n");

    css.push_str("\n/* background + colours */\nwindow {\n");
    css.push_str("  background-color: @piuma_bg;\n  color: @piuma_fg;\n}\n");

    // Borders: only the groups the bar itself would render.
    if border.is_some() {
        css.push_str("\n/* borders */\nbutton, entry {\n");
        if border.as_ref().is_some_and(|b| b.0.is_some()) {
            css.push_str("  border-color: @piuma_border;\n");
        }
        if let Some(radius) = border.as_ref().and_then(|b| b.1) {
            css.push_str(&format!("  border-radius: {radius}px;\n"));
        }
        css.push_str("}\n");
    }
    css
}

/// Border colour/radius mirroring the bar's group precedence
/// (`sensor_defaults` first, then `section_defaults`), honouring the
/// `-1 = disabled` rule. `None` = no configured border → no rule.
fn border_style(panel: &config::PanelConfig) -> Option<(Option<String>, Option<u32>)> {
    let sensor = panel.sensor_defaults.as_ref();
    let section = panel.section_defaults.as_ref();
    // The colour becomes `piuma_border` in the palette: only a parseable
    // value counts (invalid colours are ignored by the bar too).
    let color = sensor
        .and_then(|d| d.border_color.as_deref())
        .or_else(|| section.and_then(|d| d.border_color.as_deref()))
        .and_then(|c| config::parse_color(c).ok())
        .map(|c| rgb_hex(c));
    let radius = config::style_num(sensor.and_then(|d| d.border_radius))
        .or_else(|| config::style_num(section.and_then(|d| d.border_radius)));
    (color.is_some() || radius.is_some()).then_some((color, radius))
}

/// `#rrggbb` for a configured colour (all `parse_color` formats are
/// normalised, alpha dropped), or `fallback` when absent/invalid.
/// `#rrggbb` from an iced colour, alpha intentionally dropped.
fn rgb_hex(c: iced::Color) -> String {
    let byte = |f: f32| (f * 255.0).round() as u8;
    format!("#{:02x}{:02x}{:02x}", byte(c.r), byte(c.g), byte(c.b))
}

/// Write the bridge unless the file already holds this exact content
/// (an unchanged hot reload must not touch the mtime).
fn write(file: &Path, content: &str) {
    if let Some(dir) = file.parent() {
        if let Err(err) = std::fs::create_dir_all(dir) {
            eprintln!("[piuma] app theme bridge: cannot create {}: {err}", dir.display());
            return;
        }
    }
    if std::fs::read_to_string(file).ok().as_deref() == Some(content) {
        return;
    }
    match std::fs::write(file, content) {
        Ok(()) => eprintln!("[piuma] app theme bridge written: {}", file.display()),
        Err(err) => eprintln!("[piuma] app theme bridge: cannot write {}: {err}", file.display()),
    }
}

/// GTK theme dir path: `~/.local/share/themes/Piuma/gtk-{3,4}/gtk.css`.
/// piuma writes a theme that imports the base (`adw-gtk3-dark`),
/// overrides with the piuma palette, and sets character/background.
/// GTK reads it when `GTK_THEME=Piuma` is in the environment.
const THEME_DIR: &str = "Piuma";

/// Generate the GTK theme directory contents. Called when `app_theme`
/// is enabled; mirrors the config bridge but uses the GTK_THEME path.
fn sync_theme_dir(panel: &config::PanelConfig, pal: Option<&palette::Palette>) {
    let Some(base) = dirs::data_dir() else {
        return;
    };
    let dir = base.join("themes").join(THEME_DIR);
    let enabled = panel.app_theme.unwrap_or(false);
    for version in ["gtk-3.0", "gtk-4.0"] {
        let file = dir.join(version).join("gtk.css");
        if enabled {
            write_theme_file(&file, panel, pal);
        } else {
            remove_theme_ours(&file);
        }
    }
    if enabled {
        ensure_theme_dir(&dir);
    }
}

/// Create the theme dir hierarchy and an index.theme so GTK finds it.
fn ensure_theme_dir(dir: &Path) {
    for version in ["gtk-3.0", "gtk-4.0"] {
        let d = dir.join(version);
        if let Err(_) = std::fs::create_dir_all(&d) {
            return;
        }
    }
    let theme_file = dir.join("index.theme");
    if !theme_file.exists() {
        let content = "[Piuma]\nType=gnome-theme\n";
        let _ = std::fs::write(&theme_file, content);
    }
}

/// Write the theme CSS file, skipping if byte-identical.
fn write_theme_file(file: &Path, panel: &config::PanelConfig, pal: Option<&palette::Palette>) {
    let content = render_theme_css(panel, pal);
    if let Ok(existing) = std::fs::read_to_string(file) {
        if existing == content {
            return;
        }
    }
    if let Some(dir) = file.parent() {
        let _ = std::fs::create_dir_all(dir);
    }
    if let Err(e) = std::fs::write(file, content) {
        eprintln!("[piuma] GTK theme dir: cannot write {}: {e}", file.display());
    }
}

/// The GTK theme CSS: base import + palette override + character.
fn render_theme_css(panel: &config::PanelConfig, pal: Option<&palette::Palette>) -> String {
    let mut css = String::new();
    css.push_str(HEADER);
    css.push_str("\n\n");

    // Base import: GTK3 uses @import url(), GTK4 too.
    css.push_str("@import url('/usr/share/themes/adw-gtk3-dark/gtk-3.0/gtk.css');\n\n");

    // Palette overrides (the base defines `piuma_*` names that the
    // bridge rules below consume; GTK resolves them at rule time).
    css.push_str("/* palette override */\n");
    let bg = rgb_hex(crate::styles::panel_bg(panel, pal));
    let fg = rgb_hex(crate::styles::default_text(panel, pal));
    css.push_str(&format!("@define-color piuma_bg {bg};\n"));
    css.push_str(&format!("@define-color piuma_fg {fg};\n"));

    // Character
    let font = panel
        .font
        .as_deref()
        .filter(|f| !f.is_empty())
        .unwrap_or(crate::DEFAULT_FONT)
        .replace('"', "");
    let size = panel.font_size.unwrap_or(crate::DEFAULT_FONT_SIZE);
    let bold = panel.bold.unwrap_or(false);
    css.push_str("\n/* character */\n* {\n");
    css.push_str(&format!("  font-family: \"{font}\";\n"));
    css.push_str(&format!("  font-size: {size}px;\n"));
    if bold {
        css.push_str("  font-weight: bold;\n");
    }
    css.push_str("}\n");

    // Background + foreground
    css.push_str("\n/* background + colours */\n");
    css.push_str("window {\n");
    css.push_str("  background-color: @piuma_bg;\n  color: @piuma_fg;\n}\n");
    css
}

/// Remove a theme CSS file only if piuma wrote it.
fn remove_theme_ours(file: &Path) {
    if !file.exists() {
        return;
    }
    let Ok(existing) = std::fs::read_to_string(file) else { return };
    if !existing.starts_with(HEADER) {
        return;
    }
    if let Err(e) = std::fs::remove_file(file) {
        eprintln!("[piuma] GTK theme dir: cannot remove {}: {e}", file.display());
    }
}

/// Remove the entire theme dir when disabled (only if piuma controls it).
fn remove_theme_dir() {
    let Some(base) = dirs::data_dir() else {
        return;
    };
    let dir = base.join("themes").join(THEME_DIR);
    if !dir.exists() {
        return;
    }
    // Safe to remove: piuma's own dir.
    let _ = std::fs::remove_dir_all(&dir);
}


#[cfg(test)]
mod tests {
    use super::*;

    /// The default config renders the bar's built-in character and
    /// palette, and no border rule (the defaults show no border).
    #[test]
    fn render_derives_bar_style() {
        let panel = config::default_config().panel;
        let css = render(&panel, None);
        assert!(css.starts_with(HEADER), "ownership header: {css}");
        assert!(css.contains("Noto Sans"), "font: {css}");
        assert!(css.contains("font-size: 14px"), "size: {css}");
        assert!(css.contains("#0f0f14"), "built-in bg: {css}");
        assert!(css.contains("#e0e0f0"), "built-in fg: {css}");
        assert!(!css.contains("button, entry"), "no border when unconfigured: {css}");
    }

    /// Configured character/colours/borders flow into the stylesheet.
    #[test]
    fn render_honours_configured_style() {
        let mut panel = config::default_config().panel;
        panel.font = Some("JetBrains Mono".to_string());
        panel.font_size = Some(18);
        panel.bold = Some(true);
        panel.default_bg_color = Some("#112233".to_string());
        panel.default_text_color = Some("#fff".to_string());
        panel.sensor_defaults = Some(config::SensorDefaults {
            text_color: None,
            bg_color: None,
            text_color_hover: None,
            bg_color_hover: None,
            border_color: Some("#ff0000".to_string()),
            border_color_hover: None,
            border_width: None,
            border_width_hover: None,
            border_radius: Some(6),
            border_type: None,
            padding: None,
        });
        let css = render(&panel, None);
        assert!(css.contains("JetBrains Mono"), "font: {css}");
        assert!(css.contains("font-size: 18px"), "size: {css}");
        assert!(css.contains("font-weight: bold"), "bold: {css}");
        assert!(css.contains("#112233"), "bg: {css}");
        assert!(css.contains("#ffffff"), "fg normalised: {css}");
        assert!(css.contains("@define-color piuma_border #ff0000"), "border: {css}");
        assert!(css.contains("border-radius: 6px"), "radius: {css}");
        // `-1 = disabled` radius must not emit a rule.
        panel.sensor_defaults.as_mut().unwrap().border_radius = Some(-1);
        assert!(!render(&panel, None).contains("border-radius"), "disabled radius: {css}");
    }

    /// The runtime wallpaper palette wins over the configured colours,
    /// exactly like the bar renders — otherwise GTK apps would keep the
    /// tones the bar already abandoned.
    #[test]
    fn render_follows_the_runtime_palette() {
        let mut panel = config::default_config().panel;
        panel.default_bg_color = Some("#112233".to_string());
        panel.default_text_color = Some("#fff".to_string());
        let pal = palette::Palette {
            bg: "#102030".to_string(),
            card: "#000000".to_string(),
            card_hover: "#111111".to_string(),
            text: "#aabbcc".to_string(),
            text_hover: "#ddeeff".to_string(),
        };
        let css = render(&panel, Some(&pal));
        assert!(css.contains("#102030"), "palette bg: {css}");
        assert!(!css.contains("#112233"), "configured bg must lose: {css}");
        assert!(css.contains("#aabbcc"), "palette fg: {css}");
    }

    /// Enabled = the file appears next to the config; disabled = piuma's
    /// own file is removed while a user's file at the same path stays.
    #[test]
    fn sync_writes_and_removes_only_ours() {
        let dir = std::env::temp_dir().join(format!("piuma-app-theme-{}", std::process::id()));
        std::fs::create_dir_all(&dir).expect("temp dir");
        let config_path = dir.join("piuma.json");

        let mut panel = config::default_config().panel;
        panel.app_theme = Some(true);
        sync(&config_path, &panel, None);
        let file = dir.join("theme").join("gtk.css");
        assert!(file.exists(), "bridge must be generated");
        assert!(std::fs::read_to_string(&file).unwrap().starts_with(HEADER));

        // Off with a foreign file: piuma keeps its hands off.
        std::fs::write(&file, "/* user stylesheet */\n").expect("write foreign");
        panel.app_theme = None;
        sync(&config_path, &panel, None);
        assert!(file.exists(), "a file piuma did not write must stay");

    // Off with piuma's own file: stale styling must go.
        std::fs::write(&file, format!("{HEADER}\nbody {{}}\n")).expect("write ours");
        sync(&config_path, &panel, None);
        assert!(!file.exists(), "our own file must be removed");
        let _ = std::fs::remove_dir_all(&dir);
    }

    /// The theme dir CSS mirrors the bridge: palette + character + window.
    #[test]
    fn render_theme_css_derives_bar_style() {
        let panel = config::default_config().panel;
        let css = render_theme_css(&panel, None);
        assert!(css.starts_with(HEADER), "ownership header: {css}");
        assert!(css.contains("adw-gtk3-dark"), "base import: {css}");
        assert!(css.contains("Noto Sans"), "font: {css}");
        assert!(css.contains("@define-color piuma_bg"), "palette: {css}");
        assert!(css.contains("window {"), "window rule: {css}");
    }

    /// Theme block includes GTK_THEME env var.
    #[test]
    fn qt_block_includes_gtk_theme() {
        let block = qt_block();
        assert!(block.contains("GTK_THEME"), "GTK_THEME in block: {block}");
        assert!(block.contains("QT_QPA_PLATFORMTHEME"), "Qt in block: {block}");
    }
}
