fn rofi_rasi(t: &Tones, panel: &config::PanelConfig) -> String {
    let section = panel.section_defaults.as_ref();
    let sensor = panel.sensor_defaults.as_ref();
    let num = |value: Option<i32>, fallback: u32| config::style_num(value).unwrap_or(fallback);
    // Same character as the bar: family, size and weight from `panel`.
    // The bar's 10px is unreadable in a launcher window, so floor it.
    let family = panel
        .font
        .as_deref()
        .filter(|f| !f.is_empty())
        .unwrap_or(crate::DEFAULT_FONT)
        .replace('"', "");
    let size = panel.font_size.unwrap_or(crate::DEFAULT_FONT_SIZE).max(12);
    let weight = if panel.bold.unwrap_or(false) { " Bold" } else { "" };
    let font = format!("{family}{weight} {size}px");
    // Window: the section border/radius; rows: the sensor one. The bar's
    // border colours are fully transparent, and the piuma hover border
    // (`border_color_hover`) is not rendered by the bar at all — the
    // selection is marked by the hover background, so no border is drawn
    // when the colour is transparent (a 0px border keeps the rows aligned).
    let radius = num(section.and_then(|d| d.border_radius), 12);
    let (border, border_color) = rofi_border(
        section.and_then(|d| d.border_color.as_deref()),
        num(section.and_then(|d| d.border_width), 1),
    );
    let row_radius = num(sensor.and_then(|d| d.border_radius), 8);
    let (row_border, row_border_color) = rofi_border(
        sensor.and_then(|d| d.border_color.as_deref()),
        num(sensor.and_then(|d| d.border_width), 2),
    );
    let pad = num(sensor.and_then(|d| d.padding), 4);
    let main_pad = pad + 6;
    let row_v = pad + 2;
    let row_h = pad + 6;

    format!(
        r#"* {{
    font: "{font}";
    text-color: {fg};
    border-color: {border_color};
}}
window {{
    background-color: {bg};
    border: {border}px;
    border-color: {border_color};
    border-radius: {radius}px;
}}
mainbox {{
    background-color: {bg};
    spacing: {gap}px;
    padding: {main_pad}px;
}}
inputbar {{
    background-color: {sensor};
    color: {fg};
    border: 0px;
    border-radius: {row_radius}px;
    padding: {row_v}px {row_h}px;
    margin: 0px 0px {gap}px 0px;
}}
listview {{
    background-color: {bg};
    padding: 0px;
    border: 0px;
}}
entry, prompt, case-indicator, element-text, element-icon, scrollbar {{
    background-color: transparent;
    font: inherit;
}}
inputbar {{
    font: inherit;
}}
element {{
    background-color: transparent;
    color: {fg};
    border: 0px;
    border-radius: {row_radius}px;
    padding: {row_v}px {row_h}px;
}}
element selected.normal, element selected.active, element selected.urgent {{
    background-color: {hover};
    color: {hoverfg};
    border: {row_border}px;
    border-color: {row_border_color};
}}
element normal.active {{
    color: {hoverfg};
}}
"#,
        bg = t.panel_bg,
        fg = t.panel_fg,
        sensor = t.sensor_bg,
        hover = t.sensor_hover_bg,
        hoverfg = t.sensor_hover_fg,
        border_color = border_color,
        border = border,
        radius = radius,
        row_radius = row_radius,
        row_border = row_border,
        row_border_color = row_border_color,
        main_pad = main_pad,
        row_v = row_v,
        row_h = row_h,
        gap = pad + 4,
    )
}

/// A border only when the colour actually shows: a transparent border
/// would still inset the content by its width.
fn rofi_border(value: Option<&str>, width: u32) -> (u32, String) {
    match value.and_then(color) {
        Some(c) if c.a > 0.001 => (width, hex_alpha(c)),
        _ => (0, "transparent".to_string()),
    }
}

/// `#rrggbbaa` when translucent, `#rrggbb` otherwise (rofi's colour syntax).
fn hex_alpha(c: Color) -> String {
    let byte = |v: f32| (v * 255.0).round() as u8;
    if c.a >= 0.999 {
        format!("#{:02x}{:02x}{:02x}", byte(c.r), byte(c.g), byte(c.b))
    } else {
        format!("#{:02x}{:02x}{:02x}{:02x}", byte(c.r), byte(c.g), byte(c.b), byte(c.a))
    }
}

