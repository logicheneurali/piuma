    /// Resolve the layers with the bar's own precedence: wallpaper
    /// palette (keeping the configured transparency) > configured
    /// default > the next coarser layer.
    fn resolve(panel: &config::PanelConfig, pal: Option<&palette::Palette>) -> Self {
        let panel_bg = crate::styles::panel_bg(panel, pal);
        let panel_fg = crate::styles::default_text(panel, pal);
        let section = panel.section_defaults.as_ref();
        let sensor = panel.sensor_defaults.as_ref();

        // Section: palette card tone, else the configured section bg.
        let section_bg = solid(
            tone(
                pal.map(|p| palette::keep_config_alpha(&p.card, section.and_then(|d| d.bg_color.as_deref()))),
                section.and_then(|d| d.bg_color.clone()),
                panel_bg,
            ),
            panel_bg,
        );
        let section_fg = solid(
            tone(
                pal.map(|p| palette::keep_config_alpha(&p.text, section.and_then(|d| d.text_color.as_deref()))),
                section.and_then(|d| d.text_color.clone()),
                panel_fg,
            ),
            panel_bg,
        );
        let section_hover_bg = solid(
            pal.and_then(|p| color(&p.card_hover)).unwrap_or(section_bg),
            section_bg,
        );
        let section_hover_fg = solid(
            pal.and_then(|p| color(&p.text_hover)).unwrap_or(section_fg),
            section_bg,
        );

        // Sensor: palette card tone, else the configured sensor bg.
        let sensor_bg = solid(
            tone(
                pal.map(|p| palette::keep_config_alpha(&p.card, sensor.and_then(|d| d.bg_color.as_deref()))),
                sensor.and_then(|d| d.bg_color.clone()),
                section_bg,
            ),
            section_bg,
        );
        let sensor_fg = solid(
            tone(
                pal.map(|p| palette::keep_config_alpha(&p.text, sensor.and_then(|d| d.text_color.as_deref()))),
                sensor.and_then(|d| d.text_color.clone()),
                panel_fg,
            ),
            sensor_bg,
        );
        let sensor_hover_bg = solid(
            tone(
                pal.map(|p| palette::keep_config_alpha(&p.card_hover, sensor.and_then(|d| d.bg_color_hover.as_deref()))),
                sensor.and_then(|d| d.bg_color_hover.clone()),
                section_hover_bg,
            ),
            sensor_bg,
        );
        let sensor_hover_fg = solid(
            tone(
                pal.map(|p| palette::keep_config_alpha(&p.text_hover, sensor.and_then(|d| d.text_color_hover.as_deref()))),
                sensor.and_then(|d| d.text_color_hover.clone()),
                section_hover_fg,
            ),
            sensor_bg,
        );

        Self {
            panel_bg: css(panel_bg),
            panel_fg: css(panel_fg),
            panel_fg_dim: css(dim(panel_fg, panel_bg)),
            section_bg: css(section_bg),
            section_fg: css(section_fg),
            section_fg_dim: css(dim(section_fg, section_bg)),
            section_hover_bg: css(section_hover_bg),
            section_hover_fg: css(section_hover_fg),
            sensor_bg: css(sensor_bg),
            sensor_fg: css(sensor_fg),
            sensor_fg_dim: css(dim(sensor_fg, sensor_bg)),
            sensor_hover_bg: css(sensor_hover_bg),
            sensor_hover_fg: css(sensor_hover_fg),
        }
    }

