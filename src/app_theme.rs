//! GTK/Qt theme bridge (roadmap N3): writes a complete GTK theme at
//! `~/.local/share/themes/Piuma` from the bar's three palette layers.
//!
//! The generated theme is self-contained: it copies the Adwaita
//! stylesheets installed with `adw-gtk3-dark` (structure and widget
//! rules — the Adwaita schema, for both GTK3 and GTK4) and appends a
//! block that redefines Adwaita's named colours and the widgets whose
//! colour Adwaita derives from the foreground. GTK resolves colour
//! references when a rule is matched, so the appended block wins.
//!
//! Layer mapping: windows (window, headerbar, sidebar, dialog) → panel
//! palette; containers (views, lists, cards) → section palette;
//! interactive widgets (buttons, entries, combos, menus) → sensor
//! palette. Hovers use each layer's hover tone. Regenerated whenever
//! the config or the wallpaper palette changes.
//!
//! `panel.app_theme` also appends the same palette block to the user's
//! `~/.config/gtk-{3,4}.0/gtk.css` (marked, removable): GTK loads those
//! at USER priority, above any theme, so an existing customisation would
//! otherwise keep pinning the old colours.
//!
//! Qt half: Qt only reads colours from a platform theme, so the toggle
//! selects `QT_QPA_PLATFORMTHEME=kde` (the KDE plugin reads `kdeglobals`)
//! with `QT_STYLE_OVERRIDE=Fusion` (Breeze draws its own palette and
//! ignores the QPalette). The `[Colors:*]` groups of `kdeglobals` are
//! patched to the piuma palette while the toggle is on and restored from
//! a backup when it goes off. The env block lives in Hyprland's config
//! and is reloaded by the compositor, so newly launched apps pick it up.

use std::path::Path;

use iced::Color;

use crate::config;
use crate::palette;

/// Ownership marker: the first line of every generated file; also what
/// `remove_ours` checks before deleting.
const HEADER: &str = "/* generated by piuma (N3 theme bridge) — do not edit */";

/// Theme directory name (GTK_THEME value) and the base theme it copies.
const THEME_NAME: &str = "Piuma";
const BASE_THEME: &str = "/usr/share/themes/adw-gtk3-dark";
const INDEX_THEME: &str =
    "[X-GNOME-Metatheme]\nName=Piuma\nType=X-GNOME-Metatheme\nGtkTheme=Piuma\n";

fn remove_ours(file: &Path) {
    let Ok(existing) = std::fs::read_to_string(file) else { return };
    if !existing.starts_with(HEADER) { return; }
    match std::fs::remove_file(file) {
        Ok(()) => eprintln!("[piuma] app theme bridge removed: {}", file.display()),
        Err(err) => eprintln!("[piuma] app theme bridge: cannot remove {}: {err}", file.display()),
    }
}

/// Sync the theme, the user stylesheets and the Qt env with the config.
///
/// GTK loads `~/.config/gtk-{3,4}.0/gtk.css` at USER priority, above any
/// theme, so a marked block appended there is the only way the palette
/// can win over an existing user stylesheet.
pub fn sync(config_path: &Path, panel: &config::PanelConfig, pal: Option<&palette::Palette>) {
    let enabled = panel.app_theme.unwrap_or(false);
    let tones = Tones::resolve(panel, pal);

    // Legacy bridge file (previous releases kept it in the config dir).
    if let Some(dir) = config_path.parent() {
        remove_ours(&dir.join("theme").join("gtk.css"));
    }

    let block = tones.css();
    for version in ["gtk-3.0", "gtk-4.0"] {
        if let Some(dir) = dirs::config_dir() {
            apply_block(&dir.join(version).join("gtk.css"), enabled.then_some(block.as_str()));
        }
    }

    if enabled {
        install_theme(&block);
    } else {
        remove_theme_dir();
    }
    sync_qt(config_path, &tones, enabled);
}

const CSS_BEGIN: &str = "/* piuma theme begin — generated, do not edit */";
const CSS_END: &str = "/* piuma theme end */";

/// Append (or strip) the marked palette block at the END of a stylesheet:
/// last declaration wins in GTK's cascade, and the markers make the block
/// removable without touching the user's own rules.
fn apply_block(file: &Path, block: Option<&str>) {
    let existing = std::fs::read_to_string(file).unwrap_or_default();
    let Some(block) = block else {
        if existing.is_empty() { return; }
        write(file, &strip_block(&existing));
        return;
    };
    let base = strip_block(&existing);
    let prefix = if base.trim().is_empty() {
        String::new()
    } else {
        format!("{}\n", base.trim_end())
    };
    write(file, &format!("{prefix}{CSS_BEGIN}\n{block}{CSS_END}\n"));
}

/// Drop the piuma block, keeping every line the user wrote.
fn strip_block(text: &str) -> String {
    let mut out = String::new();
    let mut skipping = false;
    for line in text.lines() {
        if line.trim() == CSS_BEGIN { skipping = true; continue; }
        if skipping {
            if line.trim() == CSS_END { skipping = false; }
            continue;
        }
        out.push_str(line);
        out.push('\n');
    }
    out
}

/// The three palette layers resolved for the theme, in CSS colours.
