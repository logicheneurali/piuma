/// A CSS colour: `#rrggbb` when opaque, `rgba()` otherwise.
fn css(c: Color) -> String {
    let byte = |v: f32| (v * 255.0).round() as u8;
    if c.a >= 0.999 {
        format!("#{:02x}{:02x}{:02x}", byte(c.r), byte(c.g), byte(c.b))
    } else {
        format!("rgba({}, {}, {}, {:.3})", byte(c.r), byte(c.g), byte(c.b), c.a)
    }
}

fn color(value: &str) -> Option<Color> {
    config::parse_color(value).ok()
}

/// The first candidate that parses, else the fallback tone.
fn tone(palette_value: Option<String>, configured: Option<String>, fallback: Color) -> Color {
    palette_value
        .as_deref()
        .and_then(color)
        .or_else(|| configured.as_deref().and_then(color))
        .unwrap_or(fallback)
}

/// Flatten a translucent tone over the surface behind it: GTK paints
/// nested widgets separately, so a translucent background would blend
/// twice and drift from the bar's colour.
fn solid(c: Color, behind: Color) -> Color {
    if c.a >= 0.999 {
        return c;
    }
    Color {
        r: c.r * c.a + behind.r * (1.0 - c.a),
        g: c.g * c.a + behind.g * (1.0 - c.a),
        b: c.b * c.a + behind.b * (1.0 - c.a),
        a: 1.0,
    }
}

/// Materialise the theme: copy the Adwaita schema for both GTK versions,
/// then append the piuma block to the stylesheets GTK reads.
fn install_theme(overrides: &str) {
    let Some(base) = dirs::data_dir() else { return };
    install_theme_at(&base.join("themes").join(THEME_NAME), overrides);
}

fn install_theme_at(dest_root: &Path, overrides: &str) {
    for version in ["gtk-3.0", "gtk-4.0"] {
        let src = Path::new(BASE_THEME).join(version);
        let dst = dest_root.join(version);
        if !src.exists() {
            eprintln!("[piuma] GTK theme: base theme missing at {}", src.display());
            continue;
        }
        if let Err(err) = copy_dir(&src, &dst) {
            eprintln!("[piuma] GTK theme: cannot copy {}: {err}", src.display());
            continue;
        }
        for name in ["gtk.css", "gtk-dark.css"] {
            let Ok(base_css) = std::fs::read_to_string(src.join(name)) else { continue };
            write(&dst.join(name), &format!("{base_css}\n\n{HEADER}\n{overrides}"));
        }
    }
    write(&dest_root.join("index.theme"), INDEX_THEME);
}

/// Recursive directory copy (the base theme is small: CSS + assets).
fn copy_dir(src: &Path, dst: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(dst)?;
    for entry in std::fs::read_dir(src)? {
        let entry = entry?;
        let to = dst.join(entry.file_name());
        if entry.file_type()?.is_dir() {
            copy_dir(&entry.path(), &to)?;
        } else {
            std::fs::copy(entry.path(), &to)?;
        }
    }
    Ok(())
}

/// Qt side of the bridge: keep the marked block in Hyprland's config
/// in step with `panel.app_theme`.
fn sync_qt(panel: &config::PanelConfig) {
    let Some(dir) = dirs::config_dir() else { return; };
    let file = dir.join("hypr").join("hyprland.lua");
    if !file.exists() { return; }
    let Ok(existing) = std::fs::read_to_string(&file) else { return; };
    let enabled = panel.app_theme.unwrap_or(false);
    let Some(updated) = qt_applied(&existing, enabled) else { return; };
    if let Err(err) = std::fs::write(&file, &updated) {
        eprintln!("[piuma] Qt theme bridge: cannot write {}: {err}", file.display());
        return;
    }
    eprintln!("[piuma] Qt theme bridge {}: {}", if enabled { "written" } else { "removed" }, file.display());
    let _ = std::process::Command::new("hyprctl").args(["reload", "config-only"]).output();
}

const QT_BEGIN: &str = "-- generated by piuma (Qt theme bridge) — do not edit";
const QT_END: &str = "-- end piuma Qt theme bridge";

fn qt_block() -> String {
    format!("{QT_BEGIN}\nhl.env(\"GTK_THEME\", \"Piuma\")\nhl.env(\"QT_QPA_PLATFORMTHEME\", \"gtk3\")\n{QT_END}\n")
}

fn qt_applied(existing: &str, enabled: bool) -> Option<String> {
    if !enabled && !existing.contains(QT_BEGIN) { return None; }
    let base: String = {
        let mut out = String::new();
        let mut skipping = false;
        for line in existing.lines() {
            if line == QT_BEGIN { skipping = true; continue; }
            if skipping {
                if line == QT_END { skipping = false; }
                continue;
            }
            out.push_str(line);
            out.push('\n');
        }
        out
    };
    let target = if enabled { format!("{base}{}", qt_block()) } else { base };
    (target != existing).then_some(target)
}

/// Write unless the file already holds this exact content.
fn write(file: &Path, content: &str) {
    if let Some(dir) = file.parent() {
        if let Err(err) = std::fs::create_dir_all(dir) {
            eprintln!("[piuma] app theme bridge: cannot create {}: {err}", dir.display());
            return;
        }
    }
    if std::fs::read_to_string(file).ok().as_deref() == Some(content) { return; }
    match std::fs::write(file, content) {
        Ok(()) => eprintln!("[piuma] app theme bridge written: {}", file.display()),
        Err(err) => eprintln!("[piuma] app theme bridge: cannot write {}: {err}", file.display()),
    }
}

fn remove_theme_dir() {
    let Some(base) = dirs::data_dir() else { return; };
    let dir = base.join("themes").join(THEME_NAME);
    if !dir.exists() { return; }
    let _ = std::fs::remove_dir_all(&dir);
}

