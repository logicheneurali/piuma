//! GTK/Qt theme bridge (roadmap N3): renders the bar's style as a GTK
//! stylesheet written inside piuma's own config directory
//! (`<config dir>/theme/gtk.css`), so GTK applications can adopt the
//! bar's style through a one-time `@import` in the user's `gtk.css`.
//!
//! Three palette layers — panel (containers), section (cards/interactive),
//! sensor (hovers) — follow the Adwaita schema. piuma never edits the
//! user's GTK/Qt files, and the palette keeps its own `@piuma_*` names
//! so an existing customisation (e.g. KDE/Breeze) keeps winning where
//! it sets the same property — the bridge only fills the gaps.
//!
//! GTK_THEME path: piuma also writes a real GTK theme dir at
//! `~/.local/share/themes/Piuma` (dark: `adw-gtk3` base + piuma palette),
//! so apps that follow `GTK_THEME` pick it up automatically — no
//! `@import` needed. piuma adds `GTK_THEME=Piuma` to the env block.
//!
//! Qt half: Qt picks its platform theme from the environment only, so
//! the bridge keeps one marked `QT_QPA_PLATFORMTHEME` block in
//! Hyprland's own config (added and removed with the same toggle; the
//! only user file piuma writes, and only between its two markers).

use std::path::Path;

use crate::config;
use crate::palette;

/// Ownership marker: the first line of every generated file; also what
/// `remove_ours` checks before deleting.
const HEADER: &str = "/* generated by piuma (N3 theme bridge) — do not edit */";

fn remove_ours(file: &Path) {
    let Ok(existing) = std::fs::read_to_string(file) else { return };
    if !existing.starts_with(HEADER) { return; }
    match std::fs::remove_file(file) {
        Ok(()) => eprintln!("[piuma] app theme bridge removed: {}", file.display()),
        Err(err) => eprintln!("[piuma] app theme bridge: cannot remove {}: {err}", file.display()),
    }
}

/// Sync the bridge with the config and the runtime wallpaper palette.
pub fn sync(config_path: &Path, panel: &config::PanelConfig, pal: Option<&palette::Palette>) {
    let Some(dir) = config_path.parent() else { return; };
    let file = dir.join("theme").join("gtk.css");
    if panel.app_theme.unwrap_or(false) {
        write(&file, &render(panel, pal));
        sync_theme_dir(panel, pal);
    } else {
        remove_ours(&file);
        remove_theme_dir();
    }
    sync_qt(panel);
}

/// Qt side of the bridge: keep the marked block in Hyprland's config
/// in step with `panel.app_theme`.
fn sync_qt(panel: &config::PanelConfig) {
    let Some(dir) = dirs::config_dir() else { return; };
    let file = dir.join("hypr").join("hyprland.lua");
    if !file.exists() { return; }
    let Ok(existing) = std::fs::read_to_string(&file) else { return; };
    let enabled = panel.app_theme.unwrap_or(false);
    let Some(updated) = qt_applied(&existing, enabled) else { return; };
    if let Err(err) = std::fs::write(&file, &updated) {
        eprintln!("[piuma] Qt theme bridge: cannot write {}: {err}", file.display());
        return;
    }
    eprintln!("[piuma] Qt theme bridge {}: {}", if enabled { "written" } else { "removed" }, file.display());
    let _ = std::process::Command::new("hyprctl").args(["reload", "config-only"]).output();
}

const QT_BEGIN: &str = "-- generated by piuma (Qt theme bridge) — do not edit";
const QT_END: &str = "-- end piuma Qt theme bridge";

fn qt_block() -> String {
    format!("{QT_BEGIN}\nhl.env(\"GTK_THEME\", \"Piuma\")\nhl.env(\"QT_QPA_PLATFORMTHEME\", \"gtk3\")\n{QT_END}\n")
}

fn qt_applied(existing: &str, enabled: bool) -> Option<String> {
    if !enabled && !existing.contains(QT_BEGIN) { return None; }
    let base: String = {
        let mut out = String::new();
        let mut skipping = false;
        for line in existing.lines() {
            if line == QT_BEGIN { skipping = true; continue; }
            if skipping {
                if line == QT_END { skipping = false; }
                continue;
            }
            out.push_str(line);
            out.push('\n');
        }
        out
    };
    let target = if enabled { format!("{base}{}", qt_block()) } else { base };
    (target != existing).then_some(target)
}

/// Border colour/radius mirroring the bar's group precedence.
fn border_style(panel: &config::PanelConfig) -> Option<(Option<String>, Option<u32>)> {
    let sensor = panel.sensor_defaults.as_ref();
    let section = panel.section_defaults.as_ref();
    let color = sensor
        .and_then(|d| d.border_color.as_deref())
        .or_else(|| section.and_then(|d| d.border_color.as_deref()))
        .and_then(|c| config::parse_color(c).ok())
        .map(|c| rgb_hex(c));
    let radius = config::style_num(sensor.and_then(|d| d.border_radius))
        .or_else(|| config::style_num(section.and_then(|d| d.border_radius)));
    (color.is_some() || radius.is_some()).then_some((color, radius))
}

fn rgb_hex(c: iced::Color) -> String {
    let byte = |f: f32| (f * 255.0).round() as u8;
    format!("#{:02x}{:02x}{:02x}", byte(c.r), byte(c.g), byte(c.b))
}

/// Write the bridge unless the file already holds this exact content.
fn write(file: &Path, content: &str) {
    if let Some(dir) = file.parent() {
        if let Err(err) = std::fs::create_dir_all(dir) {
            eprintln!("[piuma] app theme bridge: cannot create {}: {err}", dir.display());
            return;
        }
    }
    if std::fs::read_to_string(file).ok().as_deref() == Some(content) { return; }
    match std::fs::write(file, content) {
        Ok(()) => eprintln!("[piuma] app theme bridge written: {}", file.display()),
        Err(err) => eprintln!("[piuma] app theme bridge: cannot write {}: {err}", file.display()),
    }
}

/// The bridge stylesheet: panel bg/fg for containers, card for
/// sections/interactive, card_hover/text_hover for hover states.
fn render(panel: &config::PanelConfig, pal: Option<&palette::Palette>) -> String {
    let font = panel
        .font
        .as_deref()
        .filter(|f| !f.is_empty())
        .unwrap_or(crate::DEFAULT_FONT)
        .replace('"', "");
    let size = panel.font_size.unwrap_or(crate::DEFAULT_FONT_SIZE);
    let bold = panel.bold.unwrap_or(false);

    let bg = rgb_hex(crate::styles::panel_bg(panel, pal));
    let fg = rgb_hex(crate::styles::default_text(panel, pal));

    // Derive card colors from the palette (borrow defaults so they stay reusable).
    let card = pal.map(|p| rgb_hex(config::parse_color(&p.card).ok().unwrap_or_default()))
        .unwrap_or_else(|| bg.clone());
    let card_hover = pal.map(|p| rgb_hex(config::parse_color(&p.card_hover).ok().unwrap_or_default()))
        .unwrap_or_else(|| bg.clone());
    let text_hover = pal.map(|p| rgb_hex(config::parse_color(&p.text_hover).ok().unwrap_or_default()))
        .unwrap_or_else(|| fg.clone());
    let border = border_style(panel);

    let mut css = String::new();
    css.push_str(HEADER);

    // Palette definitions (own names so user palette keeps winning).
    css.push_str("\n\n/* palette */\n");
    css.push_str(&format!("@define-color piuma_bg {bg};\n"));
    css.push_str(&format!("@define-color piuma_fg {fg};\n"));
    css.push_str(&format!("@define-color piuma_card {card};\n"));
    css.push_str(&format!("@define-color piuma_card_hover {card_hover};\n"));
    css.push_str(&format!("@define-color piuma_text_hover {text_hover};\n"));
    if let Some(color) = border.as_ref().and_then(|b| b.0.as_deref()) {
        css.push_str(&format!("@define-color piuma_border {color};\n"));
    }

    // Character
    css.push_str(&format!("\n/* character */\n* {{\n  font-family: \"{}\";\n  font-size: {}px;\n", font, size));
    if bold { css.push_str("  font-weight: bold;\n"); }
    css.push_str("}\n");

    // 1. Panel containers: panel bg/fg
    css.push_str("\n/* containers — panel palette */\n");
    for selector in CONTAINER_PANEL_SELECTORS {
        css.push_str(&format!("{}\n  background-color: @piuma_bg;\n  color: @piuma_fg;\n}}\n", selector));
    }

    // 1b. Popovers/menus: card bg (panel bg is too dark for popovers).
    css.push_str("\n/* popovers / menus — section palette */\n");
    for selector in POPOVER_SELECTORS {
        css.push_str(&format!("{}\n  background-color: @piuma_card;\n  color: @piuma_fg;\n}}\n", selector));
    }

    // 2. Section containers: card bg, panel fg text
    css.push_str("\n/* section containers — section palette */\n");
    for selector in CONTAINER_CARD_SELECTORS {
        css.push_str(&format!("{}\n  background-color: @piuma_card;\n  color: @piuma_fg;\n}}\n", selector));
    }

    // 3. Interactive elements: card bg, panel fg text
    css.push_str("\n/* interactive — section palette */\n");
    for selector in INTERACTIVE_SELECTORS {
        css.push_str(&format!("{}\n  background-color: @piuma_card;\n  color: @piuma_fg;\n}}\n", selector));
    }

    // 4. Interactive hover states: card_hover bg, text_hover fg
    css.push_str("\n/* interactive hover — sensor palette */\n");
    for selector in INTERACTIVE_HHOVER_SELECTORS {
        css.push_str(&format!("{}\n  background-color: @piuma_card_hover;\n  color: @piuma_text_hover;\n}}\n", selector));
    }

    // 5. Containers hover
    css.push_str("\n/* container hover — section palette */\n");
    for selector in CONTAINER_HHOVER_SELECTORS {
        css.push_str(&format!("{}\n  background-color: @piuma_card_hover;\n  color: @piuma_text_hover;\n}}\n", selector));
    }

    // Borders
    if border.is_some() {
        css.push_str("\n/* borders */\nbutton, entry {\n");
        if border.as_ref().is_some_and(|b| b.0.is_some()) {
            css.push_str("  border-color: @piuma_border;\n");
        }
        if let Some(radius) = border.as_ref().and_then(|b| b.1) {
            css.push_str(&format!("  border-radius: {radius}px;\n"));
        }
        css.push_str("}\n");
    }
    css
}

