/// GTK theme dir path: `~/.local/share/themes/Piuma/gtk-{3,4}/gtk.css`.
const THEME_DIR: &str = "Piuma";

fn sync_theme_dir(panel: &config::PanelConfig, pal: Option<&palette::Palette>) {
    let Some(base) = dirs::data_dir() else { return; };
    let dir = base.join("themes").join(THEME_DIR);
    let enabled = panel.app_theme.unwrap_or(false);
    for version in ["gtk-3.0", "gtk-4.0"] {
        let file = dir.join(version).join("gtk.css");
        if enabled {
            write_theme_file(&file, panel, pal, version);
        } else {
            remove_theme_ours(&file);
        }
    }
    if enabled { ensure_theme_dir(&dir); }
}

fn ensure_theme_dir(dir: &Path) {
    for version in ["gtk-3.0", "gtk-4.0"] {
        let d = dir.join(version);
        if let Err(_) = std::fs::create_dir_all(&d) { return; }
    }
    let theme_file = dir.join("index.theme");
    if !theme_file.exists() {
        let _ = std::fs::write(&theme_file, "[Piuma]\nType=gnome-theme\n");
    }
}

fn write_theme_file(file: &Path, panel: &config::PanelConfig, pal: Option<&palette::Palette>, gtk_version: &str) {
    let content = render_theme_css(panel, pal, gtk_version);
    if let Ok(existing) = std::fs::read_to_string(file) {
        if existing == content { return; }
    }
    if let Some(dir) = file.parent() { let _ = std::fs::create_dir_all(dir); }
    if let Err(e) = std::fs::write(file, content) {
        eprintln!("[piuma] GTK theme dir: cannot write {}: {e}", file.display());
    }
}

fn render_theme_css(panel: &config::PanelConfig, pal: Option<&palette::Palette>, gtk_version: &str) -> String {
    // GTK4: import libadwaita.css (Adwaita schema) and override its
    // @define-color names so every CSS variable / selector that uses
    // them automatically picks up piuma colors.
    // GTK3: no libadwaita available — fall back to the bridge approach.
    let use_adwaita = gtk_version == "gtk-4.0";
    let base_path: Option<&str> = if use_adwaita {
        Some("/usr/share/themes/adw-gtk3-dark/gtk-4.0/libadwaita.css")
    } else {
        None
    };

    let mut css = String::new();
    css.push_str(HEADER);

    if use_adwaita {
        css.push_str("\n\n");
        css.push_str(&format!("@import url('{}');\n\n", base_path.unwrap()));
    }

    // Piuma palette definitions.
    let bg = rgb_hex(crate::styles::panel_bg(panel, pal));
    let fg = rgb_hex(crate::styles::default_text(panel, pal));
    let card = pal.map(|p| rgb_hex(config::parse_color(&p.card).ok().unwrap_or_default())).unwrap_or_else(|| bg.clone());
    let card_hover = pal.map(|p| rgb_hex(config::parse_color(&p.card_hover).ok().unwrap_or_default())).unwrap_or_else(|| bg.clone());
    let text_hover = pal.map(|p| rgb_hex(config::parse_color(&p.text_hover).ok().unwrap_or_default())).unwrap_or_else(|| fg.clone());
    let border = border_style(panel);

    css.push_str("/* piuma palette */\n");
    css.push_str(&format!("@define-color piuma_bg {bg};\n"));
    css.push_str(&format!("@define-color piuma_fg {fg};\n"));
    css.push_str(&format!("@define-color piuma_card {card};\n"));
    css.push_str(&format!("@define-color piuma_card_hover {card_hover};\n"));
    css.push_str(&format!("@define-color piuma_text_hover {text_hover};\n"));
    if let Some(color) = border.as_ref().and_then(|b| b.0.as_deref()) {
        css.push_str(&format!("@define-color piuma_border {color};\n"));
    }

    // Adwaita @define-color overrides — every CSS variable that maps
    // to these names (e.g. --window-bg-color: @window_bg_color) now
    // resolves to our piuma colors instead of the Adwaita defaults.
    // Mapping: panel bg → containers (window/sidebar/headerbar),
    // piuma_card → cards/popovers/dialogs (popovers need lighter bg
    // than the panel).
    if use_adwaita {
        css.push_str("\n/* adwaita @define-color overrides */\n");
        css.push_str(&format!("@define-color window_bg_color {bg};\n"));
        css.push_str(&format!("@define-color window_fg_color {fg};\n"));
        css.push_str(&format!("@define-color headerbar_bg_color {bg};\n"));
        css.push_str(&format!("@define-color headerbar_fg_color {fg};\n"));
        css.push_str(&format!("@define-color headerbar_border_color {fg};\n"));
        css.push_str(&format!("@define-color sidebar_bg_color {bg};\n"));
        css.push_str(&format!("@define-color sidebar_fg_color {fg};\n"));
        css.push_str(&format!("@define-color secondary_sidebar_bg_color {bg};\n"));
        css.push_str(&format!("@define-color secondary_sidebar_fg_color {fg};\n"));
        // Cards/popovers use card bg (lighter than panel bg).
        css.push_str(&format!("@define-color card_bg_color {card};\n"));
        css.push_str(&format!("@define-color card_fg_color {fg};\n"));
        css.push_str(&format!("@define-color dialog_bg_color {card};\n"));
        css.push_str(&format!("@define-color dialog_fg_color {fg};\n"));
        css.push_str(&format!("@define-color popover_bg_color {card};\n"));
        css.push_str(&format!("@define-color popover_fg_color {fg};\n"));
        css.push_str(&format!("@define-color thumbnail_bg_color {card};\n"));
        css.push_str(&format!("@define-color thumbnail_fg_color {fg};\n"));
        // View bg/fg — used by treeviews, lists, entry backgrounds.
        css.push_str(&format!("@define-color view_bg_color {bg};\n"));
        css.push_str(&format!("@define-color view_fg_color {fg};\n"));
        // Accent — use card_hover as accent bg (hover tone for selections).
        css.push_str(&format!("@define-color accent_bg_color {card_hover};\n"));
        css.push_str(&format!("@define-color accent_fg_color {fg};\n"));
        // Semantic colors (keep Adwaita's red/green/yellow for errors/warnings).
        // shade/shade colors — keep defaults for shadows/depth.
        css.push_str("\n/* font character */\n");
        let font = panel.font.as_deref().filter(|f| !f.is_empty()).unwrap_or(crate::DEFAULT_FONT).replace('"', "");
        let size = panel.font_size.unwrap_or(crate::DEFAULT_FONT_SIZE);
        let bold = panel.bold.unwrap_or(false);
        css.push_str(&format!("* {{\n  font-family: \"{}\";\n  font-size: {}px;\n", font, size));
        if bold { css.push_str("  font-weight: bold;\n"); }
        css.push_str("}\n");

        // Padding / layout fixes for menu items, buttons, etc.
        // (Adwaita defines these in its selectors — we keep them by
        // not overriding, but add our own for menu rows.)
        css.push_str("\n/* layout — menu row padding */\n");
        css.push_str("popover.menu listview > row {\n");
        css.push_str("  padding: 4px 8px;\n");
        css.push_str("  min-height: 28px;\n");
        css.push_str("}\n");
        css.push_str("dropdown combobox popover.menu listview > row {\n");
        css.push_str("  padding: 4px 8px;\n");
        css.push_str("  min-height: 28px;\n");
        css.push_str("}\n");
        css.push_str("popover.menu listview > row:hover,\n");
        css.push_str("dropdown combobox popover.menu listview > row:hover {\n");
        css.push_str("  background-color: @piuma_card_hover;\n");
        css.push_str("  color: @piuma_text_hover;\n");
        css.push_str("}\n");

        // Container panels (background level).
        css.push_str("\n/* panel containers */\n");
        for selector in CONTAINER_PANEL_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_bg;\n  color: @piuma_fg;\n}}\n", selector));
        }

        // Popovers / menus.
        css.push_str("\n/* popovers / menus */\n");
        for selector in POPOVER_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_card;\n  color: @piuma_fg;\n}}\n", selector));
        }

        // Section containers (cards).
        css.push_str("\n/* section containers */\n");
        for selector in CONTAINER_CARD_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_card;\n  color: @piuma_fg;\n}}\n", selector));
        }

        // Interactive (buttons, entries, etc.).
        css.push_str("\n/* interactive */\n");
        for selector in INTERACTIVE_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_card;\n  color: @piuma_fg;\n}}\n", selector));
        }

        // Interactive hover.
        css.push_str("\n/* interactive hover */\n");
        for selector in INTERACTIVE_HHOVER_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_card_hover;\n  color: @piuma_text_hover;\n}}\n", selector));
        }

        // Container hover.
        css.push_str("\n/* container hover */\n");
        for selector in CONTAINER_HHOVER_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_card_hover;\n  color: @piuma_text_hover;\n}}\n", selector));
        }

        // Borders.
        if border.is_some() {
            css.push_str("\n/* borders */\nbutton, entry {\n");
            if border.as_ref().is_some_and(|b| b.0.is_some()) {
                css.push_str("  border-color: @piuma_border;\n");
            }
            if let Some(radius) = border.as_ref().and_then(|b| b.1) {
                css.push_str(&format!("  border-radius: {radius}px;\n"));
            }
            css.push_str("}\n");
        }
    } else {
        // GTK3 fallback — no libadwaita, use the bridge approach.
        css.push_str("\n\n");
        let font = panel.font.as_deref().filter(|f| !f.is_empty()).unwrap_or(crate::DEFAULT_FONT).replace('"', "");
        let size = panel.font_size.unwrap_or(crate::DEFAULT_FONT_SIZE);
        let bold = panel.bold.unwrap_or(false);
        css.push_str(&format!("/* character */\n* {{\n  font-family: \"{}\";\n  font-size: {}px;\n", font, size));
        if bold { css.push_str("  font-weight: bold;\n"); }
        css.push_str("}\n");

        css.push_str("\n/* containers — panel palette */\n");
        for selector in CONTAINER_PANEL_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_bg;\n  color: @piuma_fg;\n}}\n", selector));
        }

        css.push_str("\n/* popovers / menus — section palette */\n");
        for selector in POPOVER_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_card;\n  color: @piuma_fg;\n}}\n", selector));
        }

        css.push_str("\n/* section containers — section palette */\n");
        for selector in CONTAINER_CARD_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_card;\n  color: @piuma_fg;\n}}\n", selector));
        }

        css.push_str("\n/* interactive — section palette */\n");
        for selector in INTERACTIVE_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_card;\n  color: @piuma_fg;\n}}\n", selector));
        }

        css.push_str("\n/* interactive hover — sensor palette */\n");
        for selector in INTERACTIVE_HHOVER_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_card_hover;\n  color: @piuma_text_hover;\n}}\n", selector));
        }

        css.push_str("\n/* container hover — section palette */\n");
        for selector in CONTAINER_HHOVER_SELECTORS {
            css.push_str(&format!("{}\n  background-color: @piuma_card_hover;\n  color: @piuma_text_hover;\n}}\n", selector));
        }

        if border.is_some() {
            css.push_str("\n/* borders */\nbutton, entry {\n");
            if border.as_ref().is_some_and(|b| b.0.is_some()) {
                css.push_str("  border-color: @piuma_border;\n");
            }
            if let Some(radius) = border.as_ref().and_then(|b| b.1) {
                css.push_str(&format!("  border-radius: {radius}px;\n"));
            }
            css.push_str("}\n");
        }
    }
    css
}

fn remove_theme_ours(file: &Path) {
    if !file.exists() { return; }
    let Ok(existing) = std::fs::read_to_string(file) else { return; };
    if !existing.starts_with(HEADER) { return; }
    if let Err(e) = std::fs::remove_file(file) {
        eprintln!("[piuma] GTK theme dir: cannot remove {}: {e}", file.display());
    }
}

fn remove_theme_dir() {
    let Some(base) = dirs::data_dir() else { return; };
    let dir = base.join("themes").join(THEME_DIR);
    if !dir.exists() { return; }
    let _ = std::fs::remove_dir_all(&dir);
}

