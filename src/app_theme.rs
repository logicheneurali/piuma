//! GTK theme bridge (roadmap N3): renders the bar's **character**,
//! **background/colours** and **borders** as a GTK stylesheet written
//! inside piuma's own config directory (`<config dir>/theme/gtk.css`),
//! so GTK applications can adopt the bar's style through a one-time
//! `@import` in the user's `gtk.css`. piuma never edits the user's
//! GTK/Qt files, and the palette keeps its own `@piuma_*` names so an
//! existing customisation (e.g. KDE/Breeze) keeps winning where it sets
//! the same property — the bridge only fills the gaps.

use std::path::Path;

use crate::config;

/// Ownership marker: the first line of every generated file; also what
/// `remove_ours` checks before deleting, so a user's own stylesheet
/// living at the same path is never touched.
const HEADER: &str = "/* generated by piuma (N3 theme bridge) — do not edit */";

/// Sync the bridge with the config: generate it when `panel.app_theme`
/// is on, otherwise drop piuma's own file (a stale bridge would keep
/// styling apps after the toggle goes off). Called at startup and on
/// every config hot reload; the write itself skips unchanged content.
pub fn sync(config_path: &Path, panel: &config::PanelConfig) {
    let Some(dir) = config_path.parent() else { return };
    let file = dir.join("theme").join("gtk.css");
    if panel.app_theme.unwrap_or(false) {
        write(&file, &render(panel));
    } else {
        remove_ours(&file);
    }
}

/// The bridge stylesheet: the bar's own fallbacks apply (`panel.font`,
/// `default_bg_color`/`default_text_color`, the `-1 = disabled` rule for
/// border numbers via `style_num`), alpha is dropped on the background
/// (GTK windows are opaque) and no border rule is emitted when the bar
/// itself shows none (`sensor_defaults`/`section_defaults` unset).
fn render(panel: &config::PanelConfig) -> String {
    // Character: family/size/bold, same defaults as the bar.
    let font = panel
        .font
        .as_deref()
        .filter(|f| !f.is_empty())
        .unwrap_or(crate::DEFAULT_FONT)
        .replace('"', "");
    let size = panel.font_size.unwrap_or(crate::DEFAULT_FONT_SIZE);
    let bold = panel.bold.unwrap_or(false);
    // Background/colours, falling back to the bar's built-in palette.
    let bg = hex_or(panel.default_bg_color.as_deref(), rgb_hex(crate::DEFAULT_BG_COLOR));
    let fg = hex_or(panel.default_text_color.as_deref(), rgb_hex(crate::DEFAULT_TEXT_COLOR));
    let border = border_style(panel);

    let mut css = String::new();
    css.push_str(HEADER);
    css.push_str("\n\n/* palette (own names: the user's palette keeps winning) */\n");
    css.push_str(&format!("@define-color piuma_bg {bg};\n"));
    css.push_str(&format!("@define-color piuma_fg {fg};\n"));
    if let Some(color) = border.as_ref().and_then(|b| b.0.as_deref()) {
        css.push_str(&format!("@define-color piuma_border {color};\n"));
    }

    css.push_str("\n/* character */\n* {\n");
    css.push_str(&format!("  font-family: \"{font}\";\n"));
    css.push_str(&format!("  font-size: {size}px;\n"));
    if bold {
        css.push_str("  font-weight: bold;\n");
    }
    css.push_str("}\n");

    css.push_str("\n/* background + colours */\nwindow {\n");
    css.push_str("  background-color: @piuma_bg;\n  color: @piuma_fg;\n}\n");

    // Borders: only the groups the bar itself would render.
    if border.is_some() {
        css.push_str("\n/* borders */\nbutton, entry {\n");
        if border.as_ref().is_some_and(|b| b.0.is_some()) {
            css.push_str("  border-color: @piuma_border;\n");
        }
        if let Some(radius) = border.as_ref().and_then(|b| b.1) {
            css.push_str(&format!("  border-radius: {radius}px;\n"));
        }
        css.push_str("}\n");
    }
    css
}

/// Border colour/radius mirroring the bar's group precedence
/// (`sensor_defaults` first, then `section_defaults`), honouring the
/// `-1 = disabled` rule. `None` = no configured border → no rule.
fn border_style(panel: &config::PanelConfig) -> Option<(Option<String>, Option<u32>)> {
    let sensor = panel.sensor_defaults.as_ref();
    let section = panel.section_defaults.as_ref();
    // The colour becomes `piuma_border` in the palette: only a parseable
    // value counts (invalid colours are ignored by the bar too).
    let color = sensor
        .and_then(|d| d.border_color.as_deref())
        .or_else(|| section.and_then(|d| d.border_color.as_deref()))
        .and_then(|c| config::parse_color(c).ok())
        .map(|c| rgb_hex(c));
    let radius = config::style_num(sensor.and_then(|d| d.border_radius))
        .or_else(|| config::style_num(section.and_then(|d| d.border_radius)));
    (color.is_some() || radius.is_some()).then_some((color, radius))
}

/// `#rrggbb` for a configured colour (all `parse_color` formats are
/// normalised, alpha dropped), or `fallback` when absent/invalid.
fn hex_or(value: Option<&str>, fallback: String) -> String {
    value
        .and_then(|v| config::parse_color(v).ok())
        .map(rgb_hex)
        .unwrap_or(fallback)
}

/// `#rrggbb` from an iced colour, alpha intentionally dropped.
fn rgb_hex(c: iced::Color) -> String {
    let byte = |f: f32| (f * 255.0).round() as u8;
    format!("#{:02x}{:02x}{:02x}", byte(c.r), byte(c.g), byte(c.b))
}

/// Write the bridge unless the file already holds this exact content
/// (an unchanged hot reload must not touch the mtime).
fn write(file: &Path, content: &str) {
    if let Some(dir) = file.parent() {
        if let Err(err) = std::fs::create_dir_all(dir) {
            eprintln!("[piuma] app theme bridge: cannot create {}: {err}", dir.display());
            return;
        }
    }
    if std::fs::read_to_string(file).ok().as_deref() == Some(content) {
        return;
    }
    match std::fs::write(file, content) {
        Ok(()) => eprintln!("[piuma] app theme bridge written: {}", file.display()),
        Err(err) => eprintln!("[piuma] app theme bridge: cannot write {}: {err}", file.display()),
    }
}

/// Remove the generated file while the feature is off — but only a file
/// piuma wrote (identified by [`HEADER`]); anything else at that path
/// belongs to the user and stays untouched.
fn remove_ours(file: &Path) {
    let Ok(existing) = std::fs::read_to_string(file) else { return };
    if !existing.starts_with(HEADER) {
        return;
    }
    match std::fs::remove_file(file) {
        Ok(()) => eprintln!("[piuma] app theme bridge removed: {}", file.display()),
        Err(err) => eprintln!("[piuma] app theme bridge: cannot remove {}: {err}", file.display()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The default config renders the bar's built-in character and
    /// palette, and no border rule (the defaults show no border).
    #[test]
    fn render_derives_bar_style() {
        let panel = config::default_config().panel;
        let css = render(&panel);
        assert!(css.starts_with(HEADER), "ownership header: {css}");
        assert!(css.contains("Noto Sans"), "font: {css}");
        assert!(css.contains("font-size: 14px"), "size: {css}");
        assert!(css.contains("#0f0f14"), "built-in bg: {css}");
        assert!(css.contains("#e0e0f0"), "built-in fg: {css}");
        assert!(!css.contains("button, entry"), "no border when unconfigured: {css}");
    }

    /// Configured character/colours/borders flow into the stylesheet.
    #[test]
    fn render_honours_configured_style() {
        let mut panel = config::default_config().panel;
        panel.font = Some("JetBrains Mono".to_string());
        panel.font_size = Some(18);
        panel.bold = Some(true);
        panel.default_bg_color = Some("#112233".to_string());
        panel.default_text_color = Some("#fff".to_string());
        panel.sensor_defaults = Some(config::SensorDefaults {
            text_color: None,
            bg_color: None,
            text_color_hover: None,
            bg_color_hover: None,
            border_color: Some("#ff0000".to_string()),
            border_color_hover: None,
            border_width: None,
            border_width_hover: None,
            border_radius: Some(6),
            border_type: None,
            padding: None,
        });
        let css = render(&panel);
        assert!(css.contains("JetBrains Mono"), "font: {css}");
        assert!(css.contains("font-size: 18px"), "size: {css}");
        assert!(css.contains("font-weight: bold"), "bold: {css}");
        assert!(css.contains("#112233"), "bg: {css}");
        assert!(css.contains("#ffffff"), "fg normalised: {css}");
        assert!(css.contains("@define-color piuma_border #ff0000"), "border: {css}");
        assert!(css.contains("border-radius: 6px"), "radius: {css}");
        // `-1 = disabled` radius must not emit a rule.
        panel.sensor_defaults.as_mut().unwrap().border_radius = Some(-1);
        assert!(!render(&panel).contains("border-radius"), "disabled radius: {css}");
    }

    /// Enabled = the file appears next to the config; disabled = piuma's
    /// own file is removed while a user's file at the same path stays.
    #[test]
    fn sync_writes_and_removes_only_ours() {
        let dir = std::env::temp_dir().join(format!("piuma-app-theme-{}", std::process::id()));
        std::fs::create_dir_all(&dir).expect("temp dir");
        let config_path = dir.join("piuma.json");

        let mut panel = config::default_config().panel;
        panel.app_theme = Some(true);
        sync(&config_path, &panel);
        let file = dir.join("theme").join("gtk.css");
        assert!(file.exists(), "bridge must be generated");
        assert!(std::fs::read_to_string(&file).unwrap().starts_with(HEADER));

        // Off with a foreign file: piuma keeps its hands off.
        std::fs::write(&file, "/* user stylesheet */\n").expect("write foreign");
        panel.app_theme = None;
        sync(&config_path, &panel);
        assert!(file.exists(), "a file piuma did not write must stay");

        // Off with piuma's own file: stale styling must go.
        std::fs::write(&file, format!("{HEADER}\nbody {{}}\n")).expect("write ours");
        sync(&config_path, &panel);
        assert!(!file.exists(), "our own file must be removed");
        let _ = std::fs::remove_dir_all(&dir);
    }
}
